"""
eval/schema.py — Data schemas for the Meeting Intelligence Agent evaluation harness.

Defines standard schemas for:
1. Ground truth annotations (transcripts, speaker turns, action items, decisions, summaries).
2. Model predictions extracted by the agent pipeline.
3. Component-level and aggregate evaluation metrics (WER, F1, Owner/Due-date accuracy, Faithfulness).
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ReferenceSpeakerTurn(BaseModel):
    """Ground truth speaker segment."""
    speaker: str
    start: float = 0.0
    end: float = 0.0
    text: str


class ReferenceActionItem(BaseModel):
    """Ground truth action item."""
    description: str
    owner: Optional[str] = None
    due_date: Optional[str] = None
    priority: Optional[str] = "medium"


class ReferenceDecision(BaseModel):
    """Ground truth decision made in the meeting."""
    decision: str
    rationale: Optional[str] = None


class MeetingGroundTruth(BaseModel):
    """Complete ground truth dataset for a single meeting."""
    meeting_id: str
    title: str = ""
    language: str = "en"  # "en", "hi", "hinglish", etc.
    audio_file_path: Optional[str] = None
    reference_transcript: str
    speaker_turns: List[ReferenceSpeakerTurn] = Field(default_factory=list)
    action_items: List[ReferenceActionItem] = Field(default_factory=list)
    decisions: List[ReferenceDecision] = Field(default_factory=list)
    reference_summary: Optional[str] = None
    notes: Optional[str] = None


class PredictedActionItem(BaseModel):
    """Action item predicted by the agent."""
    description: str
    owner: Optional[str] = None
    due_date: Optional[str] = None
    priority: Optional[str] = None
    confidence: Optional[float] = 1.0


class PredictedDecision(BaseModel):
    """Decision predicted by the agent."""
    decision: str
    rationale: Optional[str] = None


class MeetingPrediction(BaseModel):
    """Candidate predictions generated by the agent."""
    meeting_id: str
    hypothesis_transcript: str = ""
    speaker_turns: List[ReferenceSpeakerTurn] = Field(default_factory=list)
    action_items: List[PredictedActionItem] = Field(default_factory=list)
    decisions: List[PredictedDecision] = Field(default_factory=list)
    generated_summary: Optional[str] = None
    node_latencies_ms: Dict[str, float] = Field(default_factory=dict)
    cost_usd: Optional[float] = None


class MeetingEvaluationResult(BaseModel):
    """Evaluation scores for a single meeting."""
    meeting_id: str
    title: str = ""

    # Transcription
    wer: Optional[float] = None
    cer: Optional[float] = None

    # Action Items
    action_item_precision: float = 0.0
    action_item_recall: float = 0.0
    action_item_f1: float = 0.0
    action_item_true_positives: int = 0
    action_item_false_positives: int = 0
    action_item_false_negatives: int = 0
    owner_accuracy: Optional[float] = None
    due_date_accuracy: Optional[float] = None

    # Decisions
    decision_precision: float = 0.0
    decision_recall: float = 0.0
    decision_f1: float = 0.0

    # Summary
    summary_faithfulness: Optional[float] = None
    summary_coverage: Optional[float] = None

    # Performance
    total_latency_ms: Optional[float] = None
    cost_usd: Optional[float] = None


class AggregateEvaluationReport(BaseModel):
    """Consolidated evaluation benchmark report across an entire test corpus."""
    run_id: str
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    dataset_name: str
    total_meetings: int

    # Aggregate metric means
    mean_wer: Optional[float] = None
    mean_action_item_precision: float = 0.0
    mean_action_item_recall: float = 0.0
    mean_action_item_f1: float = 0.0
    mean_owner_accuracy: Optional[float] = None
    mean_due_date_accuracy: Optional[float] = None
    mean_decision_f1: float = 0.0
    mean_summary_faithfulness: Optional[float] = None
    mean_latency_ms: Optional[float] = None
    estimated_cost_per_meeting_hour_usd: Optional[float] = None

    meeting_results: List[MeetingEvaluationResult] = Field(default_factory=list)
